#!/usr/bin/env node
// tools/estimates-guard.mjs — страж КЛАССА «оценочная константа без названного источника»
// (фаза Q, лекарство Q4; волна владельца, дефекты 11 и 12).
//
// ЗАЧЕМ. Витрина 2.2 показала «5,9–118 кВт·ч» и «813–2 034 человеко-часа». Обе вилки стояли на
// ставках, которые агент взял из головы, — и форма «оценка с видимыми допущениями» делала догадку
// легальной на вид. Правило трёх дверей запрещает выдумывать ЧИСЛО, но ставку внутри арифметики
// оно не ловило: числа-то на витрине считались. Владелец нашёл это глазами: «мне не нравятся такие
// сильные разбросы! Нужно уточнить в сети интернет, если ты не уверен, свести к примерно одному
// числу». Настоящие ставки нашлись в сети за две минуты.
//
// ПРАВИЛО, которое отсюда следует и которое стережёт этот файл: у каждой константы, участвующей в
// ОЦЕНКЕ мира (цена, ставка, расход, эквивалент), в комментарии назван ВНЕШНИЙ источник. Без
// источника константа не пишется — даже помеченная как допущение, потому что помеченное допущение
// тихо становится каноном (`PHILOSOPHY.md` → правило трёх дверей).
//
// ЧТО СЧИТАЕТСЯ ИСТОЧНИКОМ: ссылка (`http…`), названное слово владельца, или явная отсылка
// («источник:», «по данным», «ЯКОРЬ:»). Пустая ссылка на «отраслевую практику» без имени источником
// не является и здесь не проходит.
//
// ЧЕГО СТРАЖ НЕ ДЕЛАЕТ: он не проверяет, ПРАВ ли источник, и не ходит в сеть. Он проверяет, что
// источник НАЗВАН, — то есть что у числа есть адрес, по которому человек может поспорить.
//
// Использование:
//   node tools/estimates-guard.mjs            # константы WATCHED + ось витрины; exit 1 при находке
//   node tools/estimates-guard.mjs --selftest # красный на константе без источника, молчание на с ним
//
// [TESTED: 2026-08-21 · --selftest доказывает оба ответа механики констант И оба ответа оси
//  витрины (ставка найдена / ставка ушла — реестр протух) на фикстурах-копиях; мета-круг
//  «ставка реестра без источника» доказан красным на копии-мутанте самого стража; живой прогон
//  зелёный по kaif-stats, самому стражу и витрине.]

import fs from 'node:fs';
import path from 'node:path';
import { tempRoot } from './lib/temp-root.mjs';

// Файлы, чьи константы едут в число, которое читает посторонний человек. Сам страж в списке
// НАМЕРЕННО: реестр рукописных ставок витрины (ниже) живёт константами этого файла, и его
// источники проверяет та же механика, что и константы kaif-stats, — реестр не может завести
// ставку без источника по построению.
const WATCHED = ['tools/kaif-stats.mjs', 'tools/estimates-guard.mjs'];

// Приметы названного источника. Список короткий нарочно: чем шире примета, тем легче её
// удовлетворить пустой фразой.
// Границы слова `\b` в кириллических приметах НЕ СТАВЯТСЯ: в JS `\b` считает словом только ASCII,
// поэтому «по данным\b» не совпадает с «по данным ресторанов» — буква «м» для движка не словесная.
// Ровно этот класс оплачен уроком EXP-0032; первая редакция стража на нём и провалилась.
const SOURCE_MARKS = [
  /https?:\/\//i,
  /источник\s*:/i,
  /ЯКОРЬ\s*:/,
  /слово\s+владельца/i,
  /ЧИСЛО\s+ВЛАДЕЛЬЦА/i,
  /по\s+данным/i,
];

// Константы МЕТОДА, а не оценки мира: они не описывают внешнюю реальность и источника не требуют.
// Каждое исключение названо поимённо и с причиной — молчаливое исключение есть дыра в страже.
const METHOD_CONSTANTS = {
  IDLE_GAP_MINUTES: 'порог метода: где кончается активная работа, а не факт о мире',
  WORK_HOURS_PER_DAY: 'определение рабочего дня, принятое для арифметики',
  workHoursMonth: 'производная от рабочего дня, не внешняя ставка',
  subscriptionPlan: 'имя тарифа, а не число',
};

// ── Рукописные ставки ВИТРИНЫ — живой реестр (bugs/73 пункт «в», машинная половина) ────────────
// Ставка, вписанная РУКАМИ в прозу витрины, механике констант выше невидима: она не живёт в
// kaif-stats. Реестр ниже — единственный ЖИВОЙ список таких ставок (историческая таблица волны
// 2.2 осталась в plans/67 → «Оценочные ставки витрины»); провенанс на самой витрине запрещён
// правилом 4 «Витрины», поэтому источник называется здесь, в комментарии константы, — и попадает
// под механику констант шапки, потому что сам страж стоит в WATCHED.
// Ось сверяет пару «реестр ↔ витрина»: ставка реестра ОБЯЗАНА стоять в каждом названном файле;
// число ушло с витрины → реестр протух → красный, и строка реестра снимается ТЕМ ЖЕ движением,
// что переписало витрину (ровно так ставка «1 800 знаков» волны 2.2 молча пережила свою витрину).
// ЧЕГО ОСЬ НЕ ДЕЛАЕТ, и это сказано вслух: новую рукописную ставку МИМО реестра машина не
// распознаёт — «какое из чисел прозы является ставкой» есть суждение; эту половину держат глаза
// владельца на вычитке витрины (homeworks/06), как и записано в plans/67.

// Реестр ПУСТ с 2026-08-21 18:32 +03:00 — слово владельца (ДЗ-06, волна №3): блок «Интересные
// факты» снят из витрины 2.3 целиком вместе с Таблицей 6, и единственная рукописная ставка
// («Гарри Поттер — 77 000 слов», источник: wordcounter.net и wordcounters.com — 76 944, подсчёты
// сходятся) ушла с витрины; строка реестра снята ТЕМ ЖЕ движением — ровно та дисциплина, ради
// которой ось существует (протухший реестр = красный). Формат строки: { name, value,
// re: /паттерн с разделителями разрядов носителя/u, files: [список путей от корня] }.
const SHOWCASE_RATES = [];

// Ось витрины: root и реестр — параметрами, чтобы селфтест доказывал обе стороны на
// фикстурах-копиях с СИНТЕТИЧЕСКОЙ ставкой (bugs/62 — мутация на копии; живой реестр имеет
// право быть пустым, и селфтест от его состава не зависит).
function checkShowcase(root, rates = SHOWCASE_RATES) {
  const misses = [];
  for (const rate of rates) {
    for (const rel of rate.files) {
      const p = path.join(root, rel);
      if (!fs.existsSync(p)) { misses.push({ rate: rate.name, file: rel, why: 'файла нет' }); continue; }
      if (!rate.re.test(fs.readFileSync(p, 'utf8')))
        misses.push({ rate: rate.name, file: rel, why: `число ${rate.value} не найдено — реестр протух или ставка переписана без реестра` });
    }
  }
  return misses;
}

/**
 * Константы в шапке файла: `const NAME = <число>` верхнего уровня и `ключ: <число>,` внутри
 * объектов. Шапкой считается всё до первого объявления функции — дальше идут вычисления, где
 * числа являются частью алгоритма, а не ставками.
 */
function constantsOf(text) {
  const all = text.split(/\r?\n/);
  const headEnd = all.findIndex((l) => /^(?:function|const \w+ = \(|async function)/.test(l) && !/=\s*[\d{]/.test(l));
  const head = all.slice(0, headEnd > 0 ? headEnd : all.length);

  const found = [];
  head.forEach((line, i) => {
    const m = line.match(/^\s*(?:const\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*[:=]\s*(-?[\d_.]+)\s*[,;]?/);
    if (!m) return;
    const [, name, value] = m;
    if (name in METHOD_CONSTANTS) return;

    // Комментарии, покрывающие константу: собственный хвостовой плюс БЛИЖАЙШИЙ блок `//` выше.
    // Блок секции законно покрывает все свои константы — иначе правило заставляло бы копировать
    // один и тот же источник над каждой строкой, и он перестал бы читаться.
    // Подъём вверх прекращается на первой строке, которая не является ни комментарием, ни пустой,
    // ни частью соседнего объявления. Закрывающая скобка объекта пропускается намеренно: блок
    // комментария над `const PRICE = { … };` покрывает и константы, стоящие сразу за объектом, —
    // на этом первая редакция стража ложно покраснела на CACHE_READ_FACTOR.
    let cover = line;
    for (let j = i - 1; j >= 0; j--) {
      const prev = head[j];
      if (/^\s*\/\//.test(prev)) { cover += '\n' + prev; continue; }
      // ПУСТАЯ СТРОКА ЗАКАНЧИВАЕТ СЕКЦИЮ — и это главная граница правила. Без неё подъём
      // проскакивал через пустую строку к комментарию прайса и «покрывал» источником весь файл:
      // мутация, снявшая блок над WH_PER_TOKEN, оставалась зелёной. Страж, у которого одна
      // ссылка в шапке файла оправдывает любую константу ниже, не стережёт ничего.
      if (/^\s*$/.test(prev)) break;
      if (/^\s*[}\])];?,?\s*$/.test(prev)) continue;                              // хвост объекта/массива
      // Ключ соседнего объявления может быть в кавычках и с дефисами («'claude-haiku-4-5':») —
      // класс символов без дефиса обрывал подъём ровно на строке прайса.
      if (/^\s*(?:const\s+)?['"]?[A-Za-z_][\w.-]*['"]?\s*[:=]/.test(prev)) continue;  // соседняя константа
      break;
    }
    found.push({ name, value, line: i + 1, cover });
  });
  return found;
}

function check(text) {
  return constantsOf(text)
    .filter((c) => !SOURCE_MARKS.some((re) => re.test(c.cover)))
    .map((c) => ({ ...c }));
}

// ── Селфтест: оба ответа (EXP-0059) ────────────────────────────────────────────────────────────
function selftest() {
  const sourced = [
    '// ── Ставки ──',
    '// Средняя цена бургера в США, 2026 — по данным более чем 13 500 ресторанов.',
    'const BURGER_USD = 5.91;',
    'const HOUSEHOLD_KWH_DAY = 9.9;',
    '',
    'function main() { return BURGER_USD; }',
  ].join('\n');

  const unsourced = [
    '// ── Ставки ──',
    '// Примерно столько, по ощущениям.',
    'const WORDS_PER_HOUR = 300;',
    '',
    'function main() { return WORDS_PER_HOUR; }',
  ].join('\n');

  const method = [
    '// Порог простоя для активного времени.',
    'const IDLE_GAP_MINUTES = 5;',
    '',
    'function main() { return IDLE_GAP_MINUTES; }',
  ].join('\n');

  let bad = 0;

  const a = check(sourced);
  console.log(`${a.length === 0 ? '✅' : '❌'} источник назван: находок ${a.length} (ждали 0)`);
  if (a.length) { bad++; a.forEach((c) => console.log(`      лишнее — ${c.name}`)); }

  const b = check(unsourced);
  const fired = b.some((c) => c.name === 'WORDS_PER_HOUR');
  console.log(`${fired ? '✅' : '❌'} источника нет: ${fired ? 'страж покраснел' : 'СТРАЖ НЕ ЗАМЕТИЛ'}`);
  if (!fired) bad++;

  const c = check(method);
  console.log(`${c.length === 0 ? '✅' : '❌'} константа метода: исключена поимённо (находок ${c.length}, ждали 0)`);
  if (c.length) bad++;

  // Блок секции покрывает ВСЕ свои константы: HOUSEHOLD_KWH_DAY выше прошёл под общим комментарием
  // секции, и это законно — иначе источник пришлось бы дублировать над каждой строкой.
  const covered = !check(sourced).some((x) => x.name === 'HOUSEHOLD_KWH_DAY');
  console.log(`${covered ? '✅' : '❌'} блок секции покрывает свои константы`);
  if (!covered) bad++;

  // Ось витрины (bugs/73 «в») — обе стороны на фикстурах-копиях с СИНТЕТИЧЕСКОЙ ставкой
  // (bugs/62: живой README не трогается; живой реестр имеет право быть ПУСТЫМ — слово владельца
  // 2026-08-21 сняло единственную ставку, и селфтест от состава реестра не зависит).
  const box = tempRoot('estimates-guard-selftest');
  const synthRates = [{ name: 'TEST_RATE', value: 77000, re: /77[, ]000/u, files: ['README.md'] }];
  fs.writeFileSync(path.join(box, 'README.md'), 'EN half: more than 77,000 words.\n');
  const d = checkShowcase(box, synthRates);
  console.log(`${d.length === 0 ? '✅' : '❌'} витрина: ставка реестра найдена в фикстуре (misses ${d.length}, ждали 0)`);
  if (d.length) bad++;

  fs.writeFileSync(path.join(box, 'README.md'), 'The number was rewritten: 90,000 words now.\n');
  const e = checkShowcase(box, synthRates);
  const missFired = e.some((x) => x.rate === 'TEST_RATE');
  console.log(`${missFired ? '✅' : '❌'} витрина: ставка ушла — ${missFired ? 'страж покраснел (реестр протух)' : 'СТРАЖ НЕ ЗАМЕТИЛ'}`);
  if (!missFired) bad++;

  // Норма temp-root: зелёный прогон корень убирает, красный — оставляет уликой и называет путь.
  if (!bad) fs.rmSync(box, { recursive: true, force: true });
  else console.log('улики фикстур: ' + box);

  console.log(bad ? `\n❌ selftest FAILED — ${bad}` : '\n✅ selftest OK — красный без источника, молчание с источником; ось витрины — оба ответа');
  process.exit(bad ? 1 : 0);
}

// ── Точка входа ────────────────────────────────────────────────────────────────────────────────
if (process.argv.includes('--selftest')) selftest();

// Явный список файлов аргументами: так мутация для доказательства красного делается на КОПИИ
// файла, а живой инструмент при этом не трогается (`bugs/62` — правило «мутируй копию»).
const explicit = process.argv.slice(2).filter((a) => !a.startsWith('--'));

let bad = 0;
for (const file of (explicit.length ? explicit : WATCHED)) {
  if (!fs.existsSync(file)) { console.log(`❌ файла нет — ${file}`); bad++; continue; }
  const hits = check(fs.readFileSync(file, 'utf8'));
  if (!hits.length) { console.log(`✅ ${file} — у всех оценочных констант назван источник`); continue; }
  console.log(`❌ ${file} — константы без названного источника:`);
  for (const h of hits) console.log(`      стр. ${h.line}: ${h.name} = ${h.value}`);
  bad += hits.length;
}

// Ось витрины гоняется только дефолтным прогоном: явные файлы аргументами — это проверка
// КОНСТАНТ на копиях (bugs/62), витрина к ним отношения не имеет.
if (!explicit.length) {
  const misses = checkShowcase(process.cwd());
  if (!misses.length) {
    console.log(`✅ витрина — каждая ставка реестра (${SHOWCASE_RATES.length}) стоит в своих файлах`);
  } else {
    console.log('❌ витрина — реестр рукописных ставок разошёлся с витриной:');
    for (const m of misses) console.log(`      ${m.rate} → ${m.file}: ${m.why}`);
    bad += misses.length;
  }
}

console.log(bad
  ? '\n❌ estimates-guard: назови источник рядом с константой (ссылка · «источник:» · слово владельца)\n' +
    '   либо внеси её в METHOD_CONSTANTS с причиной, если это порог метода, а не факт о мире.'
  : '\n✅ estimates-guard: оценочных констант без источника нет');
process.exit(bad ? 1 : 0);
