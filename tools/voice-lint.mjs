// tools/voice-lint.mjs — машинная минута чек-листа портрета голоса владельца (AUTHOR_STYLOMETRY.md §7).
//
// ЗАЧЕМ. «Написано голосом владельца» — заявление, а заявление без проверки есть ложный TESTED
// (`TESTING_FRAMEWORK.md`). Портрет несёт §7 «Чек-лист самопроверки», и слой 7A там объявлен
// МАШИННОЙ МИНУТОЙ: один прогон скрипта, ноль ручного чтения. Скрипта не было — этот файл его даёт.
//
// ЧТО ЭТОТ ЛИНТЕР НЕ ДЕЛАЕТ, названное вслух (иначе он врёт про свою силу):
//   · он НЕ судит, похож ли текст на владельца. Похожесть — класс «вкус», её выносит владелец
//     (`AGENT_GUIDE.md` → «Класс "вкус"»). Линтер ловит только НАРУШЕНИЯ явных правил портрета;
//   · он работает по РУССКОМУ тексту. Правила портрета выведены из русских корпусов, и английская
//     половина витрины ими не судится вовсе — её держат содержание и структура, зеркальные русской;
//   · пункты, у которых в портрете объявлена ГРАНИЦА ЖАНРА «в документе не запускается» (A4 markdown-
//     заголовки, A5 болд, A9/A10 капс на термине), здесь НЕ проверяются: витрина — документный жанр,
//     и в нём заголовки, болд и капс на термине законны (контрпример автора — `GOAL.md:5`);
//   · слой 7E (у каждого факта назван источник) машине недоступен по построению — он остаётся
//     ручным гейтом выдачи, и его исполнение объявляется в отчёте о сдаче, а не этим прогоном;
//   · ГРАММАТИКУ он держит РОВНО НАПОЛОВИНУ, и половина названа (bugs/66 №6). Согласование
//     «который» по числу (G1) — форма, у неё нет исключений, она здесь. Падеж («замыкание цикл»)
//     и предложное управление («под наблюдение» вместо «под наблюдением») формой НЕ являются:
//     их различает морфологический разбор, которого у инструмента нет, и подделывать его
//     эвристикой значило бы менять пропуск на поток ложных срабатываний. Эту половину держат
//     глаза владельца (`homeworks/05`); таблица волны `plans/67` строка 2 исправлена, чтобы не
//     кредитовать машину за чужую работу.
//
// Использование:
//   node tools/voice-lint.mjs <файл.md> [ещё файлы…]      # проверка; exit 1 при нарушении
//   node tools/voice-lint.mjs --selftest                   # доказать, что каждый пункт умеет краснеть
//
// [TESTED: 2026-08-09 · --selftest: каждый жёсткий пункт доказан ОБОИМИ ответами — красный на
//  подсунутом нарушении и молчание на чистой фикстуре (EXP-0059).]

import fs from 'node:fs';

// ── Пункты чек-листа, разложенные по силе. HARD валит прогон, SOFT печатается справкой ──────────
// Мягкие пункты существуют потому, что коридор — не запрет: выход за него означает «посмотри
// глазами», а не «текст брак». Смешать их с жёсткими значило бы получить стража с шумом, которого
// никто не читает (норма шума текстового стража — AGENT_GUIDE, ~10 ложных на 1 настоящую).
const HARD = 'HARD';
const SOFT = 'SOFT';

/** Тело документа: без front-matter, без блоков кода, без HTML-тегов и без markdown-таблиц. */
function bodyOf(text) {
  return text
    .replace(/^---\n[\s\S]*?\n---\n/, '')            // front-matter
    .replace(/```[\s\S]*?```/g, ' ')                 // блоки кода
    // Код-спан ПЕРЕНОСИТСЯ через строку: врап проходит внутри `…`, и спан, съеденный классом без
    // переноса, утекает наружу вместе с флагами и прямыми кавычками. Ровно так линтер сообщил о
    // «двух прямых кавычках в русском абзаце», которых в тексте нет: это была команда
    // `--since "…"`, разорванная врапом. Класс исключает только бэктик, поэтому спан теперь
    // пересекает строки; потолок длины держит рассинхрон бэктиков от съедания документа.
    .replace(/`[^`]{0,300}`/g, ' ')
    .replace(/<[^>]+>/g, ' ')                        // HTML-обёртки витрины
    .replace(/^\|.*\|\s*$/gm, ' ')                   // строки таблиц: это данные, не период автора
    // МАРКЕРЫ СПИСКА — ловушка A7 самого портрета: врап склеивает «\n- пункт» в « - пункт», и
    // счётчик глифов принимает буллет за тире-знак. У автора маркированный список законен.
    .replace(/^\s*[-*+]\s+/gm, ' ')
    .replace(/^#{1,6}\s+.*$/gm, ' ');                // заголовки: не предложения
}

/** Только русские предложения — англоязычная половина витрины портретом не судится. */
function russianSentences(body) {
  return body
    .split(/(?<=[.!?…])\s+|\n{2,}/)
    .map((s) => s.replace(/\s+/g, ' ').trim())
    .filter((s) => s.length > 1)
    .filter((s) => {
      const cyr = (s.match(/[А-Яа-яЁё]/g) || []).length;
      const lat = (s.match(/[A-Za-z]/g) || []).length;
      return cyr > lat;                              // предложение считается русским по перевесу букв
    });
}

const words = (s) => (s.match(/[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z-]*/gu) || []).length;

// ── Проверки ───────────────────────────────────────────────────────────────────────────────────
function checks(text) {
  const body = bodyOf(text);
  const ru = russianSentences(body);
  const ruText = ru.join(' ');
  const total = ru.reduce((a, s) => a + words(s), 0);
  const out = [];
  const add = (level, id, ok, msg, detail = '') => out.push({ level, id, ok, msg, detail });

  // A2 — стоп-паттерн №1, единственный со строго нулевой авторской базой (портрет §7A).
  const a2 = ruText.match(/(?<![А-Яа-яЁёA-Za-z-])(?:важно|стоит|следует)\s+отметить(?![А-Яа-яЁёA-Za-z-])/giu) || [];
  add(HARD, 'A2', a2.length === 0,
      `стоп-паттерн «важно/стоит/следует отметить» — ${a2.length} (норма 0)`, a2.join(' · '));

  // A3 — хвост не вопрос: ни один из 67 текстов корпуса не кончается вопросом.
  const lastRu = ru[ru.length - 1] || '';
  add(HARD, 'A3', !/\?["»)\s]*$/u.test(lastRu),
      'последнее русское предложение не является вопросом', lastRu.slice(-80));

  // B9 — «ибо» примета ЖАНРА: в своде правил автора ноль, значит в документе тоже ноль.
  const b9 = ruText.match(/(?<![А-Яа-яЁёA-Za-z-])ибо(?![А-Яа-яЁёA-Za-z-])/giu) || [];
  add(HARD, 'B9', b9.length === 0, `«ибо» в документном жанре — ${b9.length} (норма 0)`);

  // B12 — глиф тире не смешан: два из трёх обязаны быть нулём. Формулируется ЗАПРЕТОМ (в портрете
  // у этого пункта пометка [NOT-TESTED] по провенансу — предписывающих чисел там нет).
  // Тире считается ТОЛЬКО в позиции знака препинания — портрет (П1) говорит именно о ней. Числовой
  // диапазон «813–2 034», «20–51» не является тире автора, это запись интервала: включив его,
  // страж потребовал бы выбросить диапазоны из таблицы фактов, то есть чинил бы текст под
  // собственную неточность.
  const em = (ruText.match(/(?<![0-9])\s*—\s*(?![0-9])/g) || []).length;
  const en = (ruText.match(/(?<![0-9])\s*–\s*(?![0-9])/g) || []).length;
  const hy = (ruText.match(/ - /g) || []).length;
  const nonZero = [em, en, hy].filter((n) => n > 0).length;
  add(HARD, 'B12', nonZero <= 1,
      `глифы тире: «—» ${em} · «–» ${en} · « - » ${hy} — ненулевых ${nonZero} (норма 1)`);

  // B5 (машинная часть) — на весь файл ОДИН тип кавычек.
  const guill = (ruText.match(/[«»]/g) || []).length;
  const dumb = (ruText.match(/"/g) || []).length;
  add(HARD, 'B5', !(guill > 0 && dumb > 0),
      `кавычки: «ёлочки» ${guill} · прямые ${dumb} — тип должен быть один`);

  // G1 — согласование «который» по ЧИСЛУ с придаточным сказуемым (bugs/66 №6, дефект №2 волны Q).
  // Волна владельца принесла три грамматические поломки в одном абзаце авторской символики:
  // «замыкание цикл» (падеж), «под наблюдение проектов» (управление) и «проектов, который им
  // пользуются» (согласование). Строка 2 таблицы plans/67 записала, что «класс держит voice-lint»,
  // — и это была неправда: ни один жёсткий пункт грамматики не касался, а прогон на сломанной
  // копии печатал «жёстких нарушений нет».
  //
  // Механизируется ровно ТО, ЧТО ЯВЛЯЕТСЯ ФОРМОЙ. Здесь форма чистая и без морфологии:
  // единственное «который/которая/которое» и МНОЖЕСТВЕННОЕ сказуемое в пределах короткого окна.
  // Русский требует согласования по числу, поэтому пара «который … -ют/-ут/-ат/-ят» ошибочна
  // всегда — исключений у неё нет, и ложных срабатываний она не даёт: правильный текст пишет
  // «которые … пользуются».
  //
  // ЧЕГО ЭТОТ ПУНКТ НЕ ДЕЛАЕТ, и это сказано вслух (и в шапке инструмента): падеж («замыкание
  // цикл») и предложное управление («под наблюдение» вместо «под наблюдением») формой НЕ
  // ЯВЛЯЮТСЯ — их различает морфологический разбор, которого у инструмента нет. Половина
  // грамматики остаётся за глазами владельца (`homeworks/05`), и строка 2 волны исправлена, чтобы
  // не кредитовать машину за чужую работу.
  const WINDOW = 40;   // символов между местоимением и сказуемым: длиннее — связь уже не очевидна
  const g1 = ruText.match(new RegExp(
    `(?<![А-Яа-яЁё-])котор(?:ый|ая|ое)(?![А-Яа-яЁё-])[^.!?\\n]{0,${WINDOW}}?` +
    '(?<![А-Яа-яЁё-])[а-яё]+(?:ют|ут|ат|ят)(?:ся)?(?![А-Яа-яЁё-])', 'giu')) || [];
  add(HARD, 'G1', g1.length === 0,
      `«который» единственного числа при множественном сказуемом — ${g1.length} (норма 0)`,
      g1.join(' · '));

  // A12/С11 — ритм РАЗБОРА. Длина предложения у автора КОНСТАНТА и переживает смену жанра
  // (кодекс 12,45 против прозы 12,79), поэтому коридор применим и к документу. Мягкий: выход за
  // коридор означает «посмотри глазами», а не брак.
  const avg = total / Math.max(ru.length, 1);
  const short = ru.filter((s) => words(s) <= 5).length / Math.max(ru.length, 1) * 100;
  add(SOFT, 'A12', avg >= 11 && avg <= 17.5,
      `средняя длина русского предложения ${avg.toFixed(1)} слов (коридор РАЗБОРА 11,0–17,5)`);
  add(SOFT, 'A12s', short >= 7 && short <= 19,
      `коротких предложений (≤5 слов) ${short.toFixed(1)} % (коридор РАЗБОРА 7–19 %)`);

  // B10 — «является» из РАЗБОРА не вычищается: у автора 27,1 на 10 000 слов, у машины 9,4 и 2,1,
  // то есть машина связку НЕДОБИРАЕТ. Вычистил ниже авторского уровня — вернул машинный шов.
  //
  // ⚠️ ГРАНИЦА ДОКАЗАТЕЛЬНОЙ БАЗЫ, найденная фазой Q. Оба числа замерены на СВОБОДНОЙ ПРОЗЕ; для
  // документного регистра (руководство, витрина) замера НЕТ — корпус этого регистра в ядре пуст.
  // А владелец, читая витрину, забраковал ровно определительную связку «X является Y», повторённую
  // четырежды подряд, — то есть в документном жанре пункт способен требовать ровно того, что
  // владелец отвергает. Поэтому здесь он печатает СПРАВКУ с названной границей вместо вердикта:
  // цифра остаётся полезной (плотность видно), а притязание на порог снято до появления корпуса.
  const yavl = (ruText.match(/(?<![А-Яа-яЁёA-Za-z-])явля(?:ется|ются|лся|лась)(?![А-Яа-яЁёA-Za-z-])/giu) || []).length;
  const per10k = total ? yavl / total * 10000 : 0;
  add(SOFT, 'B10', true,
      `«является» ${yavl} шт = ${per10k.toFixed(1)} на 10 000 слов — СПРАВКА без порога: ` +
      'коридор (автор 27,1 · машина 9,4) замерен на свободной прозе, для документного жанра замера нет');

  // B8 — ОПРЕДЕЛЕНИЕ ЧЕРЕЗ ПРОТИВОПОСТАВЛЕНИЕ. Первая редакция знала ровно одну форму — «не X, а Y»
  // — и была слепа к «X, А НЕ Y», то есть к самой частой. Владелец нашёл её на витрине раньше стража
  // и сказал дословно: «как меня бесит вот этот твой стиль, когда ты описываешь от противоречия,
  // контраргументами… Я ТАК НЕ ПИШУ… Нужно писать по факту текущего состояния!» Это тот же класс,
  // что EXP-0070: искать надо по ПОНЯТИЮ (противопоставление), а не по одной его записи.
  // Машина не судит, уточняет ли антитеза ФАКТ, поэтому пункт ПЕЧАТАЕТ КАЖДОЕ вхождение со строкой:
  // список — это чек-лист на переписывание прямым утверждением, а не приговор тексту.
  const FORMS = [
    ['не X, а Y', /(?<![А-Яа-яЁёA-Za-z-])не\s+[^,.;:!?]{1,40},\s+а\s+/giu],
    ['X, а не Y', /,\s+а\s+не\s+/giu],
    ['вместо', /(?<![А-Яа-яЁёA-Za-z-])вместо\s+(?:того,\s+чтобы|этого)/giu],
  ];
  const hits = [];
  body.split(/\r?\n/).forEach((line, i) => {
    if ((line.match(/[А-Яа-яЁё]/g) || []).length <= (line.match(/[A-Za-z]/g) || []).length) return;
    for (const [name, re] of FORMS) {
      for (const m of line.matchAll(re)) hits.push(`стр. ${i + 1} (${name}): …${line.slice(Math.max(0, m.index - 30), m.index + 40).trim()}…`);
    }
  });
  // Порог узкий по слову владельца «редко»: одно вхождение на 1000 слов. Выше — переписывать.
  add(SOFT, 'B8', hits.length <= Math.max(1, Math.round(total / 1000)),
      `противопоставлений — ${hits.length} на ${total} слов (порог «редко»: ${Math.max(1, Math.round(total / 1000))}); каждое обязано уточнять ФАКТ, иначе переписывается прямым утверждением`,
      hits.length ? '\n      ' + hits.join('\n      ') : '');

  return { out, stats: { sentences: ru.length, words: total } };
}

// ── Отчёт ──────────────────────────────────────────────────────────────────────────────────────
function report(file, text) {
  const { out, stats } = checks(text);
  console.log(`\n── ${file} · русских предложений ${stats.sentences} / слов ${stats.words} ──`);
  let hardFails = 0;
  for (const c of out) {
    if (c.ok) { console.log(`  ✅ ${c.id}: ${c.msg}`); continue; }
    if (c.level === HARD) { hardFails++; console.log(`  ❌ ${c.id}: ${c.msg}${c.detail ? ' — ' + c.detail : ''}`); }
    else console.log(`  ⚠️  ${c.id}: ${c.msg}`);
  }
  return hardFails;
}

// ── Селфтест: каждый жёсткий пункт доказывается ОБОИМИ ответами (EXP-0059) ──────────────────────
function selftest() {
  // Чистая фикстура: русский документный текст, проходящий все жёсткие пункты.
  const clean = [
    'Развёртывание является набором файлов, которые агент читает и ведёт.',
    'Правило простое — сначала канон, потом код.',
    'Проверка выполняется наблюдением, а запись о ней живёт в документе.',
    'Агент знает свою машину из проб.',
  ].join('\n\n');

  const mutations = [
    ['A2', clean + '\n\nВажно отметить, что канон читается перед задачей.'],
    ['A3', clean + '\n\nА зачем вообще нужен этот канон?'],
    ['B9', clean + '\n\nКанон читается первым, ибо иначе работа стоит.'],
    ['B12', clean + '\n\nЗдесь стоит другой глиф – и он смешан с первым.'],
    ['B5', clean + '\n\nОн назвал это "правилом", а не «правилом».'],
    // Дословная форма из волны владельца (bugs/66 №6): «под наблюдением проектов, который им
    // пользуются» — единственное местоимение при множественном сказуемом.
    ['G1', clean + '\n\nКанон под наблюдением проектов, который им пользуются.'],
  ];

  let bad = 0;
  const hardIds = ['A2', 'A3', 'B9', 'B12', 'B5', 'G1'];

  // 1. МОЛЧАНИЕ на чистой фикстуре — вопрос, который почти никто не задаёт.
  const cleanOut = checks(clean).out.filter((c) => c.level === HARD && !c.ok);
  const silent = cleanOut.length === 0;
  console.log(`${silent ? '✅' : '❌'} чистая фикстура: жёстких нарушений ${cleanOut.length} (ждали 0)`);
  if (!silent) { bad++; cleanOut.forEach((c) => console.log(`      лишнее срабатывание — ${c.id}: ${c.msg}`)); }

  // 2. КРАСНЫЙ на подсунутом нарушении — по одному на каждый жёсткий пункт.
  for (const [id, text] of mutations) {
    const fired = checks(text).out.find((c) => c.id === id && !c.ok);
    const others = checks(text).out.filter((c) => c.level === HARD && !c.ok && c.id !== id).map((c) => c.id);
    const ok = Boolean(fired);
    console.log(`${ok ? '✅' : '❌'} мутация ${id}: ${ok ? 'страж покраснел' : 'СТРАЖ НЕ ЗАМЕТИЛ'}` +
                (others.length ? ` (заодно сработали ${others.join(', ')} — адресность неточна)` : ''));
    if (!ok) bad++;
  }

  // 3. Границы жанра соблюдены: заголовок, болд и капс на термине в ДОКУМЕНТЕ не краснеют.
  const doc = '## Заголовок\n\n**Жирное** выделение и термин КАНОН являются законными в документе.\n\n' + clean;
  const docFails = checks(doc).out.filter((c) => c.level === HARD && !c.ok);
  const docOk = docFails.length === 0;
  console.log(`${docOk ? '✅' : '❌'} границы жанра: заголовок/болд/капс-термин в документе не краснеют (нарушений ${docFails.length}, ждали 0)`);
  if (!docOk) bad++;

  console.log(bad ? `\n❌ selftest FAILED — ${bad}` : '\n✅ selftest OK — каждый жёсткий пункт доказан красным И молчанием');
  process.exit(bad ? 1 : 0);
}

// ── Точка входа ────────────────────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
if (args.includes('--selftest')) selftest();
else if (!args.length) {
  console.log('usage: node tools/voice-lint.mjs <файл.md> [ещё файлы…] | --selftest');
  process.exit(2);
} else {
  let fails = 0;
  for (const f of args) {
    if (!fs.existsSync(f)) { console.log(`❌ файла нет — ${f}`); fails++; continue; }
    fails += report(f, fs.readFileSync(f, 'utf8'));
  }
  console.log(fails
    ? `\n❌ voice-lint: ${fails} жёстких нарушений правил портрета (AUTHOR_STYLOMETRY.md §7)`
    : '\n✅ voice-lint: жёстких нарушений нет. ⚠️ Похожесть голоса этим НЕ доказана — вердикт «это мой голос» выносит владелец (класс «вкус»).');
  process.exit(fails ? 1 : 0);
}
